#!/usr/bin/env bash
# Bring up a throwaway tailnet: Headscale + tagged nodes.
#   scripts/up.sh            # web, api, db
#   SCALE=20 scripts/up.sh   # plus 20 api-pool replicas
set -euo pipefail
cd "$(dirname "$0")/.."

hs() { docker compose --profile headscale exec -T headscale headscale "$@"; }

if [[ ! -f certs/ca.crt ]]; then
  echo "==> throwaway CA + cert for headscale (certs/)"
  mkdir -p certs
  openssl req -x509 -newkey rsa:2048 -nodes -days 365 -subj "/CN=msw test CA" \
    -keyout certs/ca.key -out certs/ca.crt 2>/dev/null
  openssl req -newkey rsa:2048 -nodes -subj "/CN=headscale" \
    -keyout certs/headscale.key -out certs/headscale.csr 2>/dev/null
  printf 'subjectAltName=DNS:headscale\nbasicConstraints=CA:FALSE\nextendedKeyUsage=serverAuth\n' > certs/ext.cnf
  openssl x509 -req -in certs/headscale.csr -CA certs/ca.crt -CAkey certs/ca.key \
    -CAcreateserial -days 365 -extfile certs/ext.cnf -out certs/headscale.crt 2>/dev/null
  rm -f certs/headscale.csr certs/ext.cnf certs/ca.srl
  chmod 644 certs/*.crt certs/headscale.key   # headscale container reads the key
fi

echo "==> starting headscale"
docker compose --profile headscale up -d --wait headscale

echo "==> user 'world'"
hs users create world >/dev/null 2>&1 || true
USER_ID=$(hs users list -o json | jq -r '.[] | select(.name=="world") | .id')

mkkey() {  # reusable + ephemeral + pre-tagged; nodes vanish 2m after going offline
  hs preauthkeys create --user "$USER_ID" --reusable --ephemeral \
     --expiration 24h --tags "tag:$1" -o json | jq -r '.key'
}

echo "==> tagged auth keys"
cat > .env <<EOF
# generated by scripts/up.sh — throwaway keys for the local headscale
COMPOSE_PROFILES=headscale
TS_AUTHKEY_WEB=$(mkkey web)
TS_AUTHKEY_API=$(mkkey api)
TS_AUTHKEY_DB=$(mkkey db)
EOF

echo "==> nodes"
docker compose up -d ${NO_BUILD:---build} web api db
if [[ -n "${SCALE:-}" ]]; then
  docker compose --profile scale up -d --scale api-pool="$SCALE" api-pool
fi

echo "==> waiting for nodes to register"
want=3; [[ -n "${SCALE:-}" ]] && want=$((3 + SCALE))
for _ in $(seq 1 60); do
  n=$(hs nodes list -o json | jq '[(. // [])[] | select(.online)] | length')
  [[ "$n" -ge "$want" ]] && break
  sleep 1
done
hs nodes list
